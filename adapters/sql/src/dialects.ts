import { type Attribute, type CanonicalModel, type Dialect } from '@dbarchitect/core';

function enumValues(a: Attribute, m: CanonicalModel): string[] | undefined {
  return a.allowedValues ?? m.enums.find((e) => e.id === a.enumRef)?.values;
}

function dec(a: Attribute, d: number): string {
  return `${a.precision ?? 18},${a.scale ?? (a.domainType === 'money' ? 2 : d)}`;
}

export const postgresql: Dialect = {
  id: 'postgresql',
  quote: (n) => `"${n.replace(/"/g, '""')}"`,
  maxDecimalPrecision: 1000,
  supportsCheck: true,
  columnType(a) {
    if (a.physicalType) return a.physicalType;
    switch (a.domainType) {
      case 'string': return a.length ? `varchar(${a.length})` : 'text';
      case 'text': case 'enum': return a.domainType === 'enum' ? 'text' : 'text';
      case 'integer': return a.generated === 'identity' ? 'integer generated by default as identity' : 'integer';
      case 'bigint': return a.generated === 'identity' ? 'bigint generated by default as identity' : 'bigint';
      case 'decimal': case 'money': return `numeric(${dec(a, 0)})`;
      case 'boolean': return 'boolean';
      case 'date': return 'date';
      case 'datetime': return 'timestamptz';
      case 'time': return 'time';
      case 'uuid': return 'uuid';
      case 'json': return 'jsonb';
      case 'binary': return 'bytea';
    }
  },
};

export const sqlserver: Dialect = {
  id: 'sqlserver',
  quote: (n) => `[${n.replace(/]/g, ']]')}]`,
  maxVarchar: 4000,
  maxDecimalPrecision: 38,
  supportsCheck: true,
  columnType(a) {
    if (a.physicalType) return a.physicalType;
    switch (a.domainType) {
      case 'string': return a.length && a.length <= 4000 ? `nvarchar(${a.length})` : 'nvarchar(max)';
      case 'text': return 'nvarchar(max)';
      case 'enum': return 'nvarchar(50)';
      case 'integer': return a.generated === 'identity' ? 'int identity(1,1)' : 'int';
      case 'bigint': return a.generated === 'identity' ? 'bigint identity(1,1)' : 'bigint';
      case 'decimal': case 'money': return `decimal(${dec(a, 0)})`;
      case 'boolean': return 'bit';
      case 'date': return 'date';
      case 'datetime': return 'datetimeoffset';
      case 'time': return 'time';
      case 'uuid': return 'uniqueidentifier';
      case 'json': return 'nvarchar(max)';
      case 'binary': return 'varbinary(max)';
    }
  },
};

export const sqlite: Dialect = {
  id: 'sqlite',
  quote: (n) => `"${n.replace(/"/g, '""')}"`,
  maxDecimalPrecision: 38,
  supportsCheck: true,
  columnType(a) {
    if (a.physicalType) return a.physicalType;
    switch (a.domainType) {
      case 'integer': case 'bigint': case 'boolean': return 'INTEGER';
      case 'decimal': case 'money': return 'NUMERIC';
      case 'binary': return 'BLOB';
      default: return 'TEXT';
    }
  },
};

export const mysql: Dialect = {
  id: 'mysql',
  quote: (n) => `\`${n.replace(/`/g, '``')}\``,
  maxVarchar: 16383,
  maxDecimalPrecision: 65,
  supportsCheck: true,
  columnType(a) {
    if (a.physicalType) return a.physicalType;
    switch (a.domainType) {
      case 'string': return a.length && a.length <= 16383 ? `varchar(${a.length})` : 'text';
      case 'text': return 'longtext';
      case 'enum': return 'varchar(50)';
      case 'integer': return a.generated === 'identity' ? 'int auto_increment' : 'int';
      case 'bigint': return a.generated === 'identity' ? 'bigint auto_increment' : 'bigint';
      case 'decimal': case 'money': return `decimal(${dec(a, 0)})`;
      case 'boolean': return 'tinyint(1)';
      case 'date': return 'date';
      case 'datetime': return 'datetime(6)';
      case 'time': return 'time';
      case 'uuid': return 'char(36)';
      case 'json': return 'json';
      case 'binary': return 'longblob';
    }
  },
};

export const dialects: Record<Dialect['id'], Dialect> = { postgresql, sqlserver, sqlite, mysql };
export { enumValues };
